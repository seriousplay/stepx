pub(super) fn draw_icon(icon: UiIcon, size: f32, color: ColorU) -> El {
    ConstrainedBox::new(Icon::new(icon.path(), color).finish())
        .with_width(size)
        .with_height(size)
        .finish()
}
impl Companion {
    pub(super) fn ui_icon(&self, icon: UiIcon, size: f32, color: ColorU) -> El {
        draw_icon(icon, size, color)
    }
}
